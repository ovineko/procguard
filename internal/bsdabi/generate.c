/*
 * Generate procguard's BSD process-record ABI constants from native headers.
 * Build and run this program on the target OS; do not cross-compile layouts.
 */
#include <sys/param.h>
#include <sys/types.h>
#include <sys/sysctl.h>

#if !defined(__DragonFly__)
#include <sys/proc.h>
#endif

#if defined(__FreeBSD__)
#include <sys/user.h>
#elif defined(__DragonFly__)
#include <sys/kinfo.h>
#include <sys/proc_common.h>
#endif

#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define OFF(type, member) ((size_t)offsetof(type, member))
#define WIDTH(type, member) ((size_t)sizeof(((type *)0)->member))

static void fail(const char *message)
{
    fprintf(stderr, "bsdabi generator: %s\n", message);
    exit(1);
}

static int supported_pair(const char *os, const char *arch)
{
#if defined(__FreeBSD__) || defined(__OpenBSD__) || defined(__NetBSD__) || defined(__DragonFly__)
#if defined(__x86_64__) || defined(__amd64__)
#define NATIVE_ARCH "amd64"
#elif defined(__aarch64__)
#define NATIVE_ARCH "arm64"
#else
#error Unsupported native BSD architecture
#endif
#endif
#if defined(__FreeBSD__)
    return strcmp(os, "freebsd") == 0 && strcmp(arch, NATIVE_ARCH) == 0 &&
        (strcmp(arch, "amd64") == 0 || strcmp(arch, "arm64") == 0);
#elif defined(__OpenBSD__)
    return strcmp(os, "openbsd") == 0 && strcmp(arch, NATIVE_ARCH) == 0 &&
        (strcmp(arch, "amd64") == 0 || strcmp(arch, "arm64") == 0);
#elif defined(__NetBSD__)
    return strcmp(os, "netbsd") == 0 && strcmp(arch, NATIVE_ARCH) == 0 &&
        (strcmp(arch, "amd64") == 0 || strcmp(arch, "arm64") == 0);
#elif defined(__DragonFly__)
    return strcmp(os, "dragonfly") == 0 && strcmp(arch, NATIVE_ARCH) == 0 &&
        strcmp(arch, "amd64") == 0;
#else
    (void)os;
    (void)arch;
    return 0;
#endif
}

static void emit_constant(const char *name, int value)
{
    printf("\t%-19s = %d\n", name, value);
}
static void emit(const char *os, const char *arch)
{
    size_t record_size, pid_offset, pid_width, pgid_offset, pgid_width;
    size_t state_offset, state_width, struct_size_offset = 0;
    size_t struct_size_width = 0;
    int proc_pgrp = 0, dead1 = 0, dead2 = 0, dead3 = 0, dead_count = 0;

#if defined(__FreeBSD__)
    typedef struct kinfo_proc record_t;
    record_size = sizeof(record_t);
    pid_offset = OFF(record_t, ki_pid); pid_width = WIDTH(record_t, ki_pid);
    pgid_offset = OFF(record_t, ki_pgid); pgid_width = WIDTH(record_t, ki_pgid);
    state_offset = OFF(record_t, ki_stat); state_width = WIDTH(record_t, ki_stat);
    struct_size_offset = OFF(record_t, ki_structsize);
    struct_size_width = WIDTH(record_t, ki_structsize);
    dead1 = SZOMB; dead_count = 1;
    proc_pgrp = KERN_PROC_PGRP;
#elif defined(__OpenBSD__)
    typedef struct kinfo_proc record_t;
    record_size = sizeof(record_t);
    pid_offset = OFF(record_t, p_pid); pid_width = WIDTH(record_t, p_pid);
    pgid_offset = OFF(record_t, p__pgid); pgid_width = WIDTH(record_t, p__pgid);
    state_offset = OFF(record_t, p_stat); state_width = WIDTH(record_t, p_stat);
    dead1 = SDEAD; dead_count = 1;
    proc_pgrp = KERN_PROC_PGRP;
#elif defined(__NetBSD__)
    typedef struct kinfo_proc2 record_t;
    record_size = sizeof(record_t);
    pid_offset = OFF(record_t, p_pid); pid_width = WIDTH(record_t, p_pid);
    pgid_offset = OFF(record_t, p__pgid); pgid_width = WIDTH(record_t, p__pgid);
    state_offset = OFF(record_t, p_realstat); state_width = WIDTH(record_t, p_realstat);
    dead1 = SZOMB; dead2 = SDYING; dead3 = SDEAD; dead_count = 3;
    proc_pgrp = KERN_PROC_PGRP;
#elif defined(__DragonFly__)
    typedef struct kinfo_proc record_t;
    record_size = sizeof(record_t);
    pid_offset = OFF(record_t, kp_pid); pid_width = WIDTH(record_t, kp_pid);
    pgid_offset = OFF(record_t, kp_pgid); pgid_width = WIDTH(record_t, kp_pgid);
    state_offset = OFF(record_t, kp_stat); state_width = WIDTH(record_t, kp_stat);
    dead1 = SZOMB; dead_count = 1;
    proc_pgrp = KERN_PROC_PGRP;
#else
#error Unsupported BSD target
#endif

    printf("// Code generated by internal/bsdabi/generate.c; DO NOT EDIT.\n");
    printf("//go:build %s && %s\n\n", os, arch);
    printf("package procguard\n\nconst (\n");
    emit_constant("bsdRecordSize", (int)record_size);
    emit_constant("bsdPIDOffset", (int)pid_offset);
    emit_constant("bsdPIDWidth", (int)pid_width);
    emit_constant("bsdPGIDOffset", (int)pgid_offset);
    emit_constant("bsdPGIDWidth", (int)pgid_width);
    emit_constant("bsdStateOffset", (int)state_offset);
    emit_constant("bsdStateWidth", (int)state_width);
    emit_constant("bsdProcPgrp", proc_pgrp);
    emit_constant("bsdDeadState1", dead1);
    emit_constant("bsdDeadState2", dead2);
    emit_constant("bsdDeadState3", dead3);
    emit_constant("bsdDeadStateCount", dead_count);
    emit_constant("bsdStructSizeOffset", (int)struct_size_offset);
    emit_constant("bsdStructSizeWidth", (int)struct_size_width);
    printf(")\n");
}

int main(int argc, char **argv)
{
    if (argc != 3)
        fail("usage: generate <goos> <goarch>");
    if (!supported_pair(argv[1], argv[2]))
        fail("requested GOOS/GOARCH does not match this supported native compiler target");
    emit(argv[1], argv[2]);
    if (ferror(stdout))
        fail("writing generated source failed");
    return 0;
}
